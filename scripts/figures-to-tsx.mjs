// Turns the approved isometric figures (design/handoff/figures/*.svg) into
// server-rendered TSX components in components/brand/figures/art.
//
//   node scripts/figures-to-tsx.mjs            all figures
//   node scripts/figures-to-tsx.mjs model-     only the files whose name contains "model-"
//
// The SVGs are machine-written by the generators in design/handoff/generators,
// so a small tag tokenizer is enough. It:
//   - renames attributes to their React names (stroke-width -> strokeWidth),
//   - namespaces ids (and url(#id) references) so several figures can share
//     one page without clashing filter ids,
//   - drops the root's class and inline style; the wrapper styles the figure.
// Animation classes inside the drawing (f1-p, lockbar, led l1 ...) are kept:
// the keyframes live in the figure's CSS module.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SRC = join(ROOT, "design/handoff/figures");
const OUT = join(ROOT, "components/brand/figures/art");

const FIGURES = [
  { file: "embedded-delivery.svg", name: "EmbeddedDeliveryArt", ns: "fig-embedded" },
  { file: "modernisation.svg", name: "ModernisationArt", ns: "fig-modern" },
  { file: "diligence.svg", name: "DiligenceArt", ns: "fig-diligence" },
  { file: "genai.svg", name: "GenAiArt", ns: "fig-genai" },
  { file: "soc2-readiness.svg", name: "Soc2Art", ns: "fig-soc2" },
  { file: "aws-cabinet.svg", name: "AwsCabinetArt", ns: "fig-aws" },
  // "The model" figures in the Work modals (round 2).
  { file: "model-slm.svg", name: "ModelSlmArt", ns: "fig-mslm", out: "components/products/models/art" },
  { file: "model-extract.svg", name: "ModelExtractArt", ns: "fig-mext", out: "components/products/models/art" },
  { file: "model-murmur.svg", name: "ModelMurmurArt", ns: "fig-mmur", out: "components/products/models/art" },
  { file: "model-morrow.svg", name: "ModelMorrowArt", ns: "fig-mmor", out: "components/products/models/art" },
];

const KEEP = new Set(["viewBox", "pathLength", "stdDeviation", "role"]);

function reactName(name) {
  if (name === "class") return "className";
  if (name.startsWith("data-") || name.startsWith("aria-") || KEEP.has(name)) return name;
  if (name === "xml:space") return "xmlSpace";
  if (name === "xlink:href") return "xlinkHref";
  return name.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
}

/** "transform-origin: 1px 2px" -> { transformOrigin: "1px 2px" } */
function styleObject(css) {
  const entries = css
    .split(";")
    .map((decl) => decl.trim())
    .filter(Boolean)
    .map((decl) => {
      const at = decl.indexOf(":");
      const prop = decl.slice(0, at).trim().replace(/-([a-z])/g, (_, c) => c.toUpperCase());
      return `${prop}: ${JSON.stringify(decl.slice(at + 1).trim())}`;
    });
  return `{ ${entries.join(", ")} }`;
}

function escapeAttr(value) {
  return value.replace(/&quot;/g, '\\"').replace(/"/g, "&quot;");
}

function convert(svg, ns) {
  const tokens = svg.matchAll(/<!--[\s\S]*?-->|<(\/?)([a-zA-Z][\w:-]*)((?:\s+[^\s=>/]+(?:="[^"]*")?)*)\s*(\/?)>|([^<]+)/g);
  const lines = [];
  let depth = 0;
  let isRoot = true;
  for (const [whole, closing, tag, rawAttrs = "", selfClosing, text] of tokens) {
    if (whole.startsWith("<!--")) continue;
    if (text !== undefined) {
      if (text.trim()) throw new Error(`unexpected text node: ${text.trim().slice(0, 40)}`);
      continue;
    }
    if (closing) {
      depth -= 1;
      lines.push(`${"  ".repeat(depth + 2)}</${tag}>`);
      continue;
    }
    const attrs = [];
    for (const [, name, value = ""] of rawAttrs.matchAll(/([^\s=]+)(?:="([^"]*)")?/g)) {
      if (name === "xmlns" || name.startsWith("xmlns:")) continue;
      if (isRoot && (name === "class" || name === "style")) continue;
      if (name === "class" && value.trim() === "") continue;
      let v = value.replace(/url\(#([^)]+)\)/g, `url(#${ns}-$1)`);
      if (name === "id") v = `${ns}-${v}`;
      if (name === "style") {
        attrs.push(`style={${styleObject(v)}}`);
        continue;
      }
      attrs.push(`${reactName(name)}="${escapeAttr(v)}"`);
    }
    if (isRoot) attrs.push("className={className}");
    isRoot = false;
    const open = `${"  ".repeat(depth + 2)}<${tag}${attrs.length ? " " + attrs.join(" ") : ""}`;
    if (selfClosing) {
      lines.push(`${open} />`);
    } else {
      lines.push(`${open}>`);
      depth += 1;
    }
  }
  return lines.join("\n");
}

const only = process.argv[2];
for (const fig of FIGURES.filter((f) => !only || f.file.includes(only))) {
  const out = fig.out ? join(ROOT, fig.out) : OUT;
  mkdirSync(out, { recursive: true });
  const svg = readFileSync(join(SRC, fig.file), "utf8").trim();
  const body = convert(svg, fig.ns);
  const source = `// Generated by scripts/figures-to-tsx.mjs from design/handoff/figures/${fig.file}.
// Do not edit by hand: change the generator or the source SVG and re-run.

export function ${fig.name}({ className }: { className?: string }) {
  return (
${body}
  );
}
`;
  writeFileSync(join(out, `${fig.name}.tsx`), source);
  console.log(`${fig.name}.tsx  ${(source.length / 1024).toFixed(0)} KB`);
}
